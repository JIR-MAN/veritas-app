/**
 * Builds the incident report (HTML for PDF, plus a JSON form). Pure functions
 * so the content can be unit-tested. The report states facts VERITAS recorded
 * and nothing more: no admissibility or chain-of-custody claims.
 */
import type { Case, Evidence, TimelineEntry } from '@/features/cases/model';
import { ISSUE_LABELS } from '@/features/cases/model';
import { formatBytes, formatDateTime } from '@/features/format';

export const APP_VERSION = '0.1.0-beta';

const esc = (s: unknown) =>
  String(s ?? '').replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[ch]!);

export const REPORT_DISCLAIMERS = [
  'This report was generated by VERITAS from information entered by the user and from checks run on the user’s device.',
  'SHA-256 fingerprints identify the exact file that was recorded. They show whether a copy is identical; they do not show whether content is genuine.',
  'Content Credentials results describe how a file says it was made. They do not prove what it depicts is true or false.',
  'This report is not legal advice. VERITAS does not certify admissibility or chain of custody. Seek advice from a qualified professional.',
  'Notes and dates marked as entered by the user have not been verified by VERITAS.',
];

export function buildReportData(c: Case, evidence: Evidence[], timeline: TimelineEntry[], generatedAt = new Date().toISOString()) {
  const tz = (() => {
    try {
      return Intl.DateTimeFormat().resolvedOptions().timeZone;
    } catch {
      return 'UTC';
    }
  })();
  return {
    format: 'veritas-incident-report',
    formatVersion: 1,
    app: { name: 'VERITAS', version: APP_VERSION },
    generatedAt,
    generatedTimeZone: tz,
    case: { id: c.id, title: c.title, category: ISSUE_LABELS[c.category], openedAt: c.createdAt },
    evidence: evidence.map((e) => ({
      fileName: e.fileName,
      mimeType: e.mimeType,
      sizeBytes: e.size,
      sha256: e.sha256,
      fingerprintedAt: e.hashedAt,
      deviceTimeZone: e.timeZone,
      fileModifiedAt: e.fileModifiedAt,
      sourceUrlAsEnteredByUser: e.sourceUrl,
      isBundledSample: e.isSample,
      contentCredentials: e.check
        ? {
            result: e.check.headline,
            verdict: e.check.verdict,
            summary: e.check.summary,
            declaredOrigin: e.check.originLabel,
            signer: e.check.signer,
            signedAt: e.check.signedAt,
            checkedAt: e.checkedAt,
            checks: e.check.checks.map((x) => ({ check: x.label, state: x.state, detail: x.detail })),
            failureCodes: e.check.failureCodes,
            engine: e.check.engine,
          }
        : null,
    })),
    chronology: [...timeline]
      .sort((a, b) => a.occurredAt.localeCompare(b.occurredAt))
      .map((t) => ({
        occurredAt: t.occurredAt,
        approximate: t.occurredApprox,
        recordedAt: t.recordedAt,
        source: t.kind === 'note' ? 'user' : 'veritas',
        text: t.text,
      })),
    disclaimers: REPORT_DISCLAIMERS,
  };
}

export type ReportData = ReturnType<typeof buildReportData>;

export function reportHtml(d: ReportData): string {
  const ev = d.evidence
    .map(
      (e, i) => `
  <section class="ev">
    <h3>Item ${i + 1}: ${esc(e.fileName)}${e.isBundledSample ? ' <span class="tag">Sample file</span>' : ''}</h3>
    <table>
      <tr><th>SHA-256</th><td class="mono">${esc(e.sha256)}</td></tr>
      <tr><th>Fingerprinted</th><td>${esc(formatDateTime(e.fingerprintedAt, e.deviceTimeZone))} (${esc(e.deviceTimeZone)}) · ${esc(e.fingerprintedAt)}</td></tr>
      <tr><th>Type / size</th><td>${esc(e.mimeType)} · ${esc(formatBytes(e.sizeBytes))} (${e.sizeBytes} bytes)</td></tr>
      ${e.fileModifiedAt ? `<tr><th>File modified</th><td>${esc(e.fileModifiedAt)} (as reported by the device)</td></tr>` : ''}
      <tr><th>Source URL</th><td>${e.sourceUrlAsEnteredByUser ? esc(e.sourceUrlAsEnteredByUser) + ' <span class="muted">(entered by user)</span>' : '<span class="muted">Not provided</span>'}</td></tr>
      <tr><th>Content Credentials</th><td>${
        e.contentCredentials
          ? `<strong>${esc(e.contentCredentials.result)}</strong><br>${esc(e.contentCredentials.summary)}${
              e.contentCredentials.signer ? `<br>Signer: ${esc(e.contentCredentials.signer)}` : ''
            }<ul>${e.contentCredentials.checks.map((c) => `<li>${esc(c.check)}: ${esc(c.detail)}</li>`).join('')}</ul>
            <span class="muted">Checked ${esc(e.contentCredentials.checkedAt ?? '')} with ${esc(e.contentCredentials.engine?.library ?? 'unknown')} ${esc(
              e.contentCredentials.engine?.libraryVersion ?? '',
            )}; trust lists of ${esc(e.contentCredentials.engine?.trustListsFetched ?? 'unknown date')}.</span>`
          : '<span class="muted">Not checked</span>'
      }</td></tr>
    </table>
  </section>`,
    )
    .join('');
  const chron = d.chronology
    .map(
      (t) =>
        `<tr><td>${esc(formatDateTime(t.occurredAt))}${t.approximate ? ' <span class="muted">(approx.)</span>' : ''}</td><td>${esc(
          t.source === 'user' ? 'User' : 'VERITAS',
        )}</td><td>${esc(t.text)}</td></tr>`,
    )
    .join('');
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(d.case.title)} – VERITAS report</title>
<style>
  @page { margin: 18mm 16mm; }
  body { font-family: -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: #0E1A2B; font-size: 10.5pt; line-height: 1.45; }
  h1 { font-size: 18pt; margin: 0 0 2pt; font-weight: 600; }
  h2 { font-size: 12pt; margin: 18pt 0 6pt; padding-bottom: 3pt; border-bottom: 1px solid #C5CCD7; font-weight: 600; }
  h3 { font-size: 11pt; margin: 12pt 0 4pt; font-weight: 600; }
  .brand { color: #0D6E66; font-size: 9pt; letter-spacing: .12em; text-transform: uppercase; font-weight: 600; }
  .muted { color: #556275; }
  .mono { font-family: Menlo, Consolas, monospace; font-size: 9pt; word-break: break-all; }
  table { width: 100%; border-collapse: collapse; }
  th, td { text-align: left; vertical-align: top; padding: 4pt 6pt; border-bottom: 1px solid #E6E9EE; }
  th { width: 28%; color: #556275; font-weight: 500; }
  ul { margin: 4pt 0; padding-left: 14pt; }
  .tag { font-size: 8pt; background: #FBF0DC; color: #9A5B00; padding: 1pt 5pt; border-radius: 6pt; font-weight: 500; }
  .note { background: #F5F6F8; padding: 8pt 10pt; border-radius: 6pt; }
  .ev { page-break-inside: avoid; }
</style></head><body>
  <div class="brand">VERITAS · Incident report</div>
  <h1>${esc(d.case.title)}</h1>
  <div class="muted">${esc(d.case.category)} · Generated ${esc(formatDateTime(d.generatedAt))} (${esc(d.generatedTimeZone)}) · VERITAS ${esc(d.app.version)}</div>
  <h2>About this report</h2>
  <div class="note"><ul>${d.disclaimers.map((x) => `<li>${esc(x)}</li>`).join('')}</ul></div>
  <h2>Evidence (${d.evidence.length})</h2>
  ${ev || '<p class="muted">No files recorded.</p>'}
  <h2>Chronology</h2>
  <table><tr><th style="width:26%">When</th><th style="width:12%">Source</th><th>What</th></tr>${chron}</table>
</body></html>`;
}
