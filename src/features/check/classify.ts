/**
 * Turns a raw Content Credentials (C2PA) report from the on-device engine into
 * the plain-language result the user sees.
 *
 * Rules that must never be broken (from the VERITAS spec):
 *  - No credentials means "origin unknown". Never "real", never "fake".
 *  - A valid camera-capture credential says where the file came from. It does
 *    NOT prove the scene depicted is true.
 *  - Broken or tampered credentials are reported as a failed validation.
 *  - Every result lists the checks that ran and the checks that did not.
 */

export type EngineInfo = {
  library: string;
  libraryVersion: string;
  trustListsFetched: string;
  trustLists: string[];
  testAnchorsLoaded?: boolean;
};

type StatusEntry = { code: string; url?: string; explanation?: string };

export type MetaFinding = { kind: 'ai_declared' | 'generator' | 'generation_settings'; source: string; value: string };
export type MetadataReport = {
  findings: MetaFinding[];
  fields: { label: string; value: string }[];
  hasLocation: boolean;
  hasCamera: boolean;
  hasAnyMetadata: boolean;
};

export type EngineReport = {
  hasManifest: boolean;
  metadata?: MetadataReport | null;
  remoteManifestUrl?: string;
  activeLabel?: string | null;
  store?: {
    active_manifest?: string;
    manifests?: Record<string, RawManifest>;
    validation_status?: StatusEntry[];
    validation_state?: 'Invalid' | 'Valid' | 'Trusted' | string;
    validation_results?: {
      activeManifest?: { success?: StatusEntry[]; informational?: StatusEntry[]; failure?: StatusEntry[] };
    };
  };
  engine: EngineInfo;
};

type RawManifest = {
  title?: string;
  claim_generator?: string;
  claim_generator_info?: { name?: string; version?: string }[];
  assertions?: { label: string; data?: any }[];
  ingredients?: { title?: string; active_manifest?: string; relationship?: string }[];
  signature_info?: { issuer?: string; common_name?: string; time?: string; alg?: string };
};

export type EngineResponse =
  | { type: 'result'; id: string; report: EngineReport }
  | { type: 'error'; id: string; code: string; message: string; metadata?: MetadataReport | null };

export type Verdict =
  | 'ai_declared'
  | 'capture_declared'
  | 'credentials_valid'
  | 'signer_unrecognized'
  | 'credentials_invalid'
  | 'remote_not_checked'
  | 'no_credentials'
  | 'ai_metadata'
  | 'unsupported'
  | 'too_large'
  | 'failed';

export type Tone = 'neutral' | 'info' | 'caution' | 'critical';

export type CheckLine = {
  id: 'credentials' | 'signature' | 'integrity' | 'signer' | 'origin' | 'metadata' | 'watermark' | 'detector';
  label: string;
  state: 'pass' | 'fail' | 'warn' | 'info' | 'not_run' | 'unavailable';
  detail: string;
};

export type Origin = 'ai' | 'ai_composite' | 'capture' | 'digital_creation' | 'other' | null;

export type Classification = {
  verdict: Verdict;
  tone: Tone;
  headline: string;
  summary: string;
  origin: Origin;
  originLabel: string | null;
  signer: string | null;
  signedAt: string | null;
  generator: string | null;
  trustSource: 'official' | 'legacy' | 'test' | null;
  checks: CheckLine[];
  limitations: string[];
  failureCodes: string[];
  engine: EngineInfo | null;
  metadata: MetadataReport | null;
};

const AI_TYPES = new Set(['trainedAlgorithmicMedia', 'algorithmicMedia', 'algorithmicallyEnhanced']);
const AI_COMPOSITE_TYPES = new Set(['compositeWithTrainedAlgorithmicMedia', 'compositeSynthetic']);
const CAPTURE_TYPES = new Set(['digitalCapture', 'computationalCapture']);
const CREATION_TYPES = new Set(['digitalCreation', 'minorHumanEdits', 'humanEdits', 'composite', 'compositeCapture']);

/** Status codes that are about trust, not about the file being altered. */
const TRUST_CODES = new Set([
  'signingCredential.untrusted',
  'signingCredential.ocsp.skipped',
  'signingCredential.ocsp.inaccessible',
  'timeStamp.untrusted',
]);

function sourceTypeName(uri: unknown): string | null {
  if (typeof uri !== 'string' || !uri) return null;
  const tail = uri.split('/').filter(Boolean).pop();
  return tail ?? null;
}

/** Collects every digitalSourceType declared in a manifest's actions. */
function declaredSourceTypes(m: RawManifest | undefined): string[] {
  const out: string[] = [];
  for (const a of m?.assertions ?? []) {
    if (!a.label.startsWith('c2pa.actions')) continue;
    for (const act of a.data?.actions ?? []) {
      const t = sourceTypeName(act?.digitalSourceType);
      if (t) out.push(t);
    }
  }
  return out;
}

function originOf(types: string[]): Origin {
  if (types.some((t) => AI_TYPES.has(t))) return 'ai';
  if (types.some((t) => AI_COMPOSITE_TYPES.has(t))) return 'ai_composite';
  if (types.some((t) => CAPTURE_TYPES.has(t))) return 'capture';
  if (types.some((t) => CREATION_TYPES.has(t))) return 'digital_creation';
  return types.length ? 'other' : null;
}

const ORIGIN_LABEL: Record<Exclude<Origin, null>, string> = {
  ai: 'Generated by AI',
  ai_composite: 'Contains AI-generated elements',
  capture: 'Captured by a camera or recording device',
  digital_creation: 'Created or edited digitally',
  other: 'Origin declared (unrecognised type)',
};

const NOT_RUN_EXTRAS: CheckLine[] = [
  {
    id: 'watermark',
    label: 'Invisible watermark',
    state: 'unavailable',
    detail: 'Not checked yet. Use “Invisible watermark” below to read Adobe’s TrustMark on this device, or “Search the web and SynthID” for Google’s watermark.',
  },
  {
    id: 'detector',
    label: 'AI forensic detector',
    state: 'unavailable',
    detail: 'Not checked. Paid detection services are switched off until approved.',
  },
];

const BASE_LIMITATIONS = [
  'Content Credentials record how a file says it was made. They do not prove that what it shows really happened.',
  'Most files online have no credentials. Social media often removes them on upload.',
];

function generatorName(m: RawManifest | undefined): string | null {
  const info = m?.claim_generator_info?.[0];
  if (info?.name) return info.version ? `${info.name} ${info.version}` : info.name;
  return m?.claim_generator ?? null;
}

function trustSourceOf(report: EngineReport): Classification['trustSource'] {
  const ok = report.store?.validation_results?.activeManifest?.success ?? [];
  const trusted = ok.find((s) => s.code === 'signingCredential.trusted');
  if (!trusted) return null;
  const why = trusted.explanation ?? '';
  if (/user_anchors|user anchors/i.test(why) || /allowed/i.test(why)) {
    return report.engine?.testAnchorsLoaded ? 'test' : 'legacy';
  }
  return 'official';
}

function empty(verdict: Verdict, tone: Tone, headline: string, summary: string, checks: CheckLine[], engine: EngineInfo | null, limitations: string[] = BASE_LIMITATIONS): Classification {
  return {
    verdict,
    tone,
    headline,
    summary,
    origin: null,
    originLabel: null,
    signer: null,
    signedAt: null,
    generator: null,
    trustSource: null,
    checks,
    limitations,
    failureCodes: [],
    engine,
    metadata: null,
  };
}

export function describeFindings(m: MetadataReport): string {
  const parts: string[] = [];
  const declared = m.findings.find((f) => f.kind === 'ai_declared');
  if (declared) parts.push('labelled as AI-generated');
  const gens = m.findings.filter((f) => f.kind === 'generator').map((f) => f.value);
  if (gens.length) parts.push(`mentions ${gens.join(', ')}`);
  if (m.findings.some((f) => f.kind === 'generation_settings')) parts.push('contains AI image-generation settings');
  return parts.join('; ');
}

function metadataLine(m: MetadataReport | null | undefined): CheckLine {
  if (!m) return { id: 'metadata', label: 'Hidden file details', state: 'not_run', detail: 'Could not be read.' };
  if (m.findings.length) return { id: 'metadata', label: 'Hidden file details', state: 'warn', detail: `The file’s details ${describeFindings(m)}. Labels like this are easy to add or remove.` };
  if (!m.hasAnyMetadata) return { id: 'metadata', label: 'Hidden file details', state: 'info', detail: 'None found. Many apps and websites remove them.' };
  return { id: 'metadata', label: 'Hidden file details', state: 'info', detail: m.hasCamera ? 'No AI labels. Camera details are present, but they can be edited.' : 'No AI labels found.' };
}

/** Adds the metadata check, and lets an AI label lead the result when nothing stronger is known. */
function withMetadata(c: Classification, m: MetadataReport | null | undefined): Classification {
  const line = metadataLine(m);
  const i = c.checks.findIndex((x) => x.id === 'watermark');
  const checks = [...c.checks.slice(0, i), line, ...c.checks.slice(i)];
  const out = { ...c, checks, metadata: m ?? null };
  if (m?.findings.length && (c.verdict === 'no_credentials' || c.verdict === 'remote_not_checked')) {
    return {
      ...out,
      verdict: 'ai_metadata',
      tone: 'caution',
      headline: 'AI label in file details',
      summary: `This file’s hidden details ${describeFindings(m)}. That is a strong clue, but such labels can be added or removed by anyone, so it isn’t proof.`,
    };
  }
  return out;
}

export function classify(res: EngineResponse): Classification {
  const m = res.type === 'result' ? res.report.metadata : res.metadata;
  const base = classifyCredentials(res);
  return res.type === 'error' && !m ? base : withMetadata(base, m);
}

function classifyCredentials(res: EngineResponse): Classification {
  if (res.type === 'error') {
    if (res.code === 'unsupported') {
      return empty(
        'unsupported',
        'neutral',
        'File type not supported',
        'Content Credentials can’t be read from this kind of file, or the file isn’t what its name suggests.',
        [{ id: 'credentials', label: 'Content Credentials', state: 'not_run', detail: 'This file format is not supported.' }, ...NOT_RUN_EXTRAS],
        null,
      );
    }
    if (res.code === 'too_large') {
      return empty(
        'too_large',
        'neutral',
        'File too large to check here',
        'This file is larger than the on-device limit. You can still protect it as evidence.',
        [{ id: 'credentials', label: 'Content Credentials', state: 'not_run', detail: 'Skipped because of file size.' }, ...NOT_RUN_EXTRAS],
        null,
      );
    }
    return empty(
      'failed',
      'caution',
      'Check could not finish',
      'Something went wrong while reading this file. No conclusion can be drawn.',
      [{ id: 'credentials', label: 'Content Credentials', state: 'not_run', detail: `The check stopped with an error (${res.code}).` }, ...NOT_RUN_EXTRAS],
      null,
    );
  }

  const report = res.report;

  if (report.remoteManifestUrl) {
    return empty(
      'remote_not_checked',
      'info',
      'Credentials stored online',
      'This file points to Content Credentials kept on a website. VERITAS did not fetch them, so the website can’t learn which file you are checking.',
      [
        { id: 'credentials', label: 'Content Credentials', state: 'warn', detail: 'Stored online. Not fetched, to protect your privacy.' },
        ...NOT_RUN_EXTRAS,
      ],
      report.engine,
    );
  }

  if (!report.hasManifest || !report.store?.manifests) {
    return empty(
      'no_credentials',
      'neutral',
      'Origin unknown',
      'This file has no Content Credentials. That does not mean it is real or fake.',
      [
        { id: 'credentials', label: 'Content Credentials', state: 'info', detail: 'None found in this file.' },
        ...NOT_RUN_EXTRAS,
      ],
      report.engine,
    );
  }

  const store = report.store;
  const active = store.active_manifest ? store.manifests?.[store.active_manifest] : undefined;
  const status = store.validation_status ?? [];
  const failures = status.filter((s) => !TRUST_CODES.has(s.code));
  const untrusted = status.some((s) => s.code === 'signingCredential.untrusted');
  const failureCodes = failures.map((f) => f.code);
  const signatureFailed = failures.some((f) => f.code.startsWith('claimSignature') || f.code.startsWith('signingCredential'));
  const integrityFailed = failures.some((f) => f.code.startsWith('assertion.') || f.code.startsWith('claim.') || f.code.startsWith('manifest.'));
  const invalid = store.validation_state === 'Invalid' || failures.length > 0;

  const activeTypes = declaredSourceTypes(active);
  let origin = originOf(activeTypes);
  // An edit of an AI-generated ingredient still contains AI-generated material.
  if (origin !== 'ai' && origin !== 'ai_composite') {
    const ingredientTypes = (active?.ingredients ?? [])
      .map((i) => (i.active_manifest ? store.manifests?.[i.active_manifest] : undefined))
      .flatMap((m) => declaredSourceTypes(m));
    const ingOrigin = originOf(ingredientTypes);
    if (ingOrigin === 'ai' || ingOrigin === 'ai_composite') origin = 'ai_composite';
  }

  const signer = active?.signature_info?.common_name || active?.signature_info?.issuer || null;
  const issuer = active?.signature_info?.issuer || null;
  const signerLabel = signer && issuer && signer !== issuer ? `${signer} (${issuer})` : signer;
  const trustSource = invalid || untrusted ? null : trustSourceOf(report);

  const checks: CheckLine[] = [
    { id: 'credentials', label: 'Content Credentials', state: 'pass', detail: 'Found in this file.' },
    {
      id: 'signature',
      label: 'Signature',
      state: signatureFailed ? 'fail' : 'pass',
      detail: signatureFailed ? 'The signature does not match. The credentials may have been forged or damaged.' : 'Cryptographically valid.',
    },
    {
      id: 'integrity',
      label: 'File unchanged since signing',
      state: integrityFailed ? 'fail' : 'pass',
      detail: integrityFailed ? 'The file was changed after the credentials were signed.' : 'The file matches what was signed.',
    },
    {
      id: 'signer',
      label: 'Signer',
      state: untrusted ? 'warn' : invalid ? 'not_run' : 'pass',
      detail: untrusted
        ? `${signerLabel ?? 'Unknown signer'} is not on a recognised trust list.`
        : invalid
          ? 'Not assessed because validation failed.'
          : `${signerLabel ?? 'Signer'} is on ${trustSource === 'official' ? 'the C2PA trust list' : trustSource === 'test' ? 'the test trust list (test build only)' : 'the CAI legacy trust list'}.`,
    },
    {
      id: 'origin',
      label: 'Declared origin',
      state: origin ? 'info' : 'not_run',
      detail: origin ? ORIGIN_LABEL[origin] : 'No origin declared in the credentials.',
    },
    ...NOT_RUN_EXTRAS,
  ];

  const base = {
    origin,
    originLabel: origin ? ORIGIN_LABEL[origin] : null,
    signer: signerLabel,
    signedAt: active?.signature_info?.time ?? null,
    generator: generatorName(active),
    trustSource,
    checks,
    failureCodes,
    engine: report.engine,
    metadata: null,
  };

  if (invalid) {
    return {
      ...base,
      verdict: 'credentials_invalid',
      tone: 'critical',
      headline: 'Credentials failed validation',
      summary: integrityFailed
        ? 'This file was changed after it was signed. Don’t rely on what its credentials say.'
        : 'The credentials could not be verified. Don’t rely on what they say.',
      limitations: [
        'A failed check means the credentials can’t be trusted. It does not by itself prove the content is fake.',
        ...BASE_LIMITATIONS.slice(1),
      ],
    };
  }

  if (untrusted) {
    return {
      ...base,
      verdict: 'signer_unrecognized',
      tone: 'caution',
      headline: 'Signed by an unrecognised source',
      summary: origin
        ? `The credentials say: “${ORIGIN_LABEL[origin]}”. They are intact, but the signer isn’t on a recognised trust list, so treat this claim with care.`
        : 'The credentials are intact, but the signer isn’t on a recognised trust list.',
      limitations: ['Anyone can sign credentials. An unrecognised signer could be legitimate, or could be making false claims.', ...BASE_LIMITATIONS],
    };
  }

  if (origin === 'ai' || origin === 'ai_composite') {
    return {
      ...base,
      verdict: 'ai_declared',
      tone: 'info',
      headline: origin === 'ai' ? 'AI generation declared' : 'AI-generated elements declared',
      summary: `Valid credentials from ${signerLabel ?? 'a trusted signer'} state that this file ${origin === 'ai' ? 'was generated by AI' : 'contains AI-generated material'}.`,
      limitations: BASE_LIMITATIONS,
    };
  }

  if (origin === 'capture') {
    return {
      ...base,
      verdict: 'capture_declared',
      tone: 'info',
      headline: 'Camera origin recorded',
      summary: `Valid credentials from ${signerLabel ?? 'a trusted signer'} record that this file came from a capture device. This shows where the file came from, not that the scene is true.`,
      limitations: [
        'A camera can photograph a screen, a staged scene or another fake. Capture credentials can’t rule that out.',
        ...BASE_LIMITATIONS,
      ],
    };
  }

  return {
    ...base,
    verdict: 'credentials_valid',
    tone: 'info',
    headline: 'Valid credentials',
    summary: `Valid credentials from ${signerLabel ?? 'a trusted signer'}. They don’t declare whether AI was used.`,
    limitations: BASE_LIMITATIONS,
  };
}
